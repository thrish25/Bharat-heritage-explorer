/**
 * Reconstruction API Routes
 * Royal Indian Heritage Platform
 * 
 * Express/HTTP route handlers for digital reconstruction status, preview, and generation.
 * Security: Validates requests, never reveals credentials, caches results to prevent accidental loops.
 */

import type { IncomingMessage, ServerResponse } from 'node:http';
import {
  getMaskedApiKeyStatus,
  GEMINI_CONFIG
} from '../config/geminiConfig.ts';
import {
  generateHistoricalReconstruction,
  previewReconstructionPayload
} from '../services/geminiImageService.ts';
import {
  getLatestReconstruction,
  listAllReconstructions
} from '../utils/imageStorage.ts';

// Helper to write JSON response
export function sendJson(res: ServerResponse, statusCode: number, data: any) {
  res.writeHead(statusCode, {
    'Content-Type': 'application/json',
    'Access-Control-Allow-Origin': '*',
    'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
    'Access-Control-Allow-Headers': 'Content-Type'
  });
  res.end(JSON.stringify(data, null, 2));
}

// Helper to parse incoming JSON body
export function parseJsonBody(req: IncomingMessage): Promise<any> {
  return new Promise((resolve) => {
    let body = '';
    req.on('data', chunk => {
      body += chunk;
      // Protect against overly large payloads (max 1MB)
      if (body.length > 1e6) {
        req.destroy();
      }
    });
    req.on('end', () => {
      if (!body.trim()) return resolve({});
      try {
        resolve(JSON.parse(body));
      } catch {
        resolve({});
      }
    });
  });
}

/**
 * Handles incoming HTTP requests for /api/reconstruction/*
 */
export async function handleReconstructionRoute(
  req: IncomingMessage,
  res: ServerResponse,
  urlPath: string
): Promise<boolean> {
  // CORS Preflight
  if (req.method === 'OPTIONS') {
    res.writeHead(204, {
      'Access-Control-Allow-Origin': '*',
      'Access-Control-Allow-Methods': 'GET, POST, OPTIONS',
      'Access-Control-Allow-Headers': 'Content-Type'
    });
    res.end();
    return true;
  }

  // 1. GET /api/reconstruction/status
  if (req.method === 'GET' && urlPath === '/api/reconstruction/status') {
    const maskedStatus = getMaskedApiKeyStatus();
    const latest = getLatestReconstruction();
    const preview = previewReconstructionPayload();

    sendJson(res, 200, {
      status: 'ok',
      service: 'Royal Heritage Platform — Gemini Reconstruction Service',
      version: '3.0.0',
      timestamp: new Date().toISOString(),
      apiKeyStatus: maskedStatus,
      modelConfig: {
        modelId: GEMINI_CONFIG.modelId,
        endpoint: GEMINI_CONFIG.apiEndpoint,
        timeoutSeconds: GEMINI_CONFIG.timeoutMs / 1000
      },
      hasCachedReconstruction: latest !== null,
      latestReconstruction: latest,
      preparedPromptPreview: preview
    });
    return true;
  }

  // 2. GET /api/reconstruction/hampi/stone-chariot/latest
  if (req.method === 'GET' && urlPath === '/api/reconstruction/hampi/stone-chariot/latest') {
    const latest = getLatestReconstruction();
    if (latest) {
      sendJson(res, 200, { success: true, metadata: latest });
    } else {
      sendJson(res, 404, {
        success: false,
        message: 'No previous reconstruction generation found on disk. Perform a deliberate generation first.'
      });
    }
    return true;
  }

  // 3. GET /api/reconstruction/hampi/stone-chariot/history
  if (req.method === 'GET' && urlPath === '/api/reconstruction/hampi/stone-chariot/history') {
    const all = listAllReconstructions();
    sendJson(res, 200, {
      success: true,
      totalCount: all.length,
      generations: all
    });
    return true;
  }

  // 4. POST /api/reconstruction/hampi/stone-chariot/generate
  if (req.method === 'POST' && urlPath === '/api/reconstruction/hampi/stone-chariot/generate') {
    const body = await parseJsonBody(req);
    const forceNew = body.force === true;

    // Check cache to avoid accidental duplicate expensive calls
    if (!forceNew) {
      const cached = getLatestReconstruction();
      if (cached) {
        console.log('[ReconstructionRoute] Returning cached reconstruction metadata (pass force: true to generate a new image)');
        sendJson(res, 200, {
          success: true,
          cached: true,
          message: 'Returning existing cached reconstruction. Use force: true to regenerate.',
          metadata: cached
        });
        return true;
      }
    }

    // Execute generation via Gemini Image Service
    const result = await generateHistoricalReconstruction();
    if (result.success) {
      sendJson(res, 200, {
        success: true,
        cached: false,
        message: 'Reconstruction successfully generated by Google Gemini and saved to disk.',
        metadata: result.metadata
      });
    } else {
      const statusCode = result.error?.code === 'MISSING_API_KEY' ? 400 : 502;
      sendJson(res, statusCode, {
        success: false,
        error: result.error
      });
    }
    return true;
  }

  return false;
}
